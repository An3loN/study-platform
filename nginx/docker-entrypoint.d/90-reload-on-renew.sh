#!/bin/sh
# Перечитывать конфигурацию раз в шесть часов.
#
# Certbot обновляет сертификат в общем томе, но nginx держит открытым старый
# файл и сам о подмене не узнает. Перезагрузка конфигурации бесплатна и
# соединения не рвёт, поэтому проще делать её по расписанию, чем городить
# уведомление между контейнерами.
while :; do
    sleep 6h
    nginx -s reload 2>/dev/null || true
done &

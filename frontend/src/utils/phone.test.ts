import { describe, expect, it } from 'vitest'
import { isPhoneComplete, maskPhone, phoneDigits } from './phone'

/**
 * Маска телефона.
 *
 * Тонкость здесь одна, но существенная: код страны поле рисует само, поэтому
 * значение никогда не пустое и «введён ли номер» нельзя проверять через
 * required. И вставленный целиком номер надо резать с начала, а не с конца —
 * потерю последних цифр в маске не заметить.
 */

describe('phoneDigits', () => {
  it('оставляет от набранного одни цифры', () => {
    expect(phoneDigits('+7 999 123-45-67')).toBe('9991234567')
  })

  it('пустое остаётся пустым', () => {
    expect(phoneDigits('')).toBe('')
    expect(phoneDigits('+7')).toBe('')
  })

  it.each([
    ['9991234567', 'набран без кода'],
    ['+79991234567', 'вставлен с плюсом'],
    ['89991234567', 'вставлен с восьмёркой'],
    ['8 (999) 123-45-67', 'с восьмёркой и оформлением'],
    ['+7 (999) 123-45-67', 'с плюсом и оформлением'],
  ])('распознаёт %s (%s)', (input) => {
    expect(phoneDigits(input)).toBe('9991234567')
  })

  it('лишний код отрезает с начала, а не хвост', () => {
    // 8 999 123-45-67 → если резать с конца, потеряется «67»
    expect(phoneDigits('89991234567')).toBe('9991234567')
    expect(phoneDigits('89991234567').endsWith('67')).toBe(true)
  })

  it('не режет номер, начинающийся на 7 или 8, если он и так нужной длины', () => {
    expect(phoneDigits('7001234567')).toBe('7001234567')
    expect(phoneDigits('8001234567')).toBe('8001234567')
  })

  it('лишние цифры сверх десяти отбрасывает', () => {
    expect(phoneDigits('99912345678888')).toBe('9991234567')
  })

  it('не считает семёрку из значения поля частью номера', () => {
    // Значение поля всегда начинается с «+», и эту семёрку рисует само поле
    expect(phoneDigits('+7 700 123-45-67')).toBe('7001234567')
  })
})

describe('maskPhone', () => {
  it('пустое поле всё равно показывает код страны', () => {
    expect(maskPhone('')).toBe('+7')
  })

  it.each([
    ['9', '+7 9'],
    ['999', '+7 999'],
    ['9991', '+7 999 1'],
    ['999123', '+7 999 123'],
    ['9991234', '+7 999 123-4'],
    ['999123456', '+7 999 123-45-6'],
    ['9991234567', '+7 999 123-45-67'],
  ])('набор посимвольно: %s → %s', (typed, shown) => {
    expect(maskPhone(typed)).toBe(shown)
  })

  it('приводит вставленный номер к общему виду', () => {
    expect(maskPhone('89991234567')).toBe('+7 999 123-45-67')
    expect(maskPhone('+7 (999) 123-45-67')).toBe('+7 999 123-45-67')
  })

  it('устойчива к повторному применению', () => {
    // Поле пересобирает значение на каждый ввод — маска не должна «расти»
    const once = maskPhone('9991234567')
    expect(maskPhone(once)).toBe(once)
  })

  it('удаление цифры укорачивает номер, а не ломает его', () => {
    const full = maskPhone('9991234567')
    const shortened = maskPhone(full.slice(0, -1))

    expect(shortened).toBe('+7 999 123-45-6')
  })
})

describe('isPhoneComplete', () => {
  it('пустое поле с одним кодом страны — не введён', () => {
    expect(isPhoneComplete('')).toBe(false)
    expect(isPhoneComplete('+7')).toBe(false)
  })

  it('неполный номер — не введён', () => {
    expect(isPhoneComplete('+7 999 123')).toBe(false)
    expect(isPhoneComplete('+7 999 123-45-6')).toBe(false)
  })

  it('полный номер — введён', () => {
    expect(isPhoneComplete('+7 999 123-45-67')).toBe(true)
    expect(isPhoneComplete('89991234567')).toBe(true)
  })
})
